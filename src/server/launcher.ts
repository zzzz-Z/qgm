export function buildLauncher(): string {
  return '(function () {\n'
    + '  if (window.__aiRunnerLauncher) return\n'
    + '  window.__aiRunnerLauncher = true\n'
    + '  var host = document.createElement("div")\n'
    + '  host.id = "__ai-runner-host"\n'
    + '  host.style.cssText = "all:initial;position:fixed;z-index:2147483000;"\n'
    + '  document.body.appendChild(host)\n'
    + '  var shadow = host.attachShadow({ mode: "open" })\n'
    + '  var style = document.createElement("style")\n'
    + '  style.textContent = [\n'
    + '    ":host{all:initial}",\n'
    + '    "*{box-sizing:border-box;font-family:-apple-system,BlinkMacSystemFont,sans-serif}",\n'
    + '    ".fab{position:fixed;right:16px;bottom:16px;width:32px;height:32px;border-radius:50%;background:#2563eb;color:#fff;border:0;cursor:pointer;display:flex;align-items:center;justify-content:center;font-size:14px;line-height:1;box-shadow:0 2px 8px rgba(37,99,235,0.38);transition:transform 0.18s,background 0.18s;user-select:none}",\n'
    + '    ".fab:hover{transform:scale(1.08);background:#1d4ed8}",\n'
    + '    ".fab.open{background:#ef4444;box-shadow:0 4px 14px rgba(239,68,68,0.42)}",\n'
    + '    ".panel{position:fixed;inset:0 0 0 auto;width:min(1100px,90vw);background:#fff;box-shadow:-8px 0 32px rgba(15,30,60,0.18);transform:translateX(100%);transition:transform 0.25s cubic-bezier(0.4,0,0.2,1);display:flex;flex-direction:column}",\n'
    + '    ".panel.open{transform:translateX(0)}",\n'
    + '    ".panel iframe{flex:1;border:0;width:100%;background:#f5f7fa}"\n'
    + '  ].join("")\n'
    + '  shadow.appendChild(style)\n'
    + '  var fab = document.createElement("button")\n'
    + '  fab.className = "fab"\n'
    + '  fab.id = "fab"\n'
    + '  fab.title = "AI Runner (Ctrl+Shift+A)"\n'
    + '  fab.textContent = "⚡"\n'
    + '  shadow.appendChild(fab)\n'
    + '  var panel = document.createElement("div")\n'
    + '  panel.className = "panel"\n'
    + '  panel.id = "panel"\n'
    + '  var frame = document.createElement("iframe")\n'
    + '  frame.id = "frame"\n'
    + '  frame.src = "about:blank"\n'
    + '  panel.appendChild(frame)\n'
    + '  shadow.appendChild(panel)\n'
    + '  var isOpen = false\n'
    + '  function toggle() {\n'
    + '    isOpen = !isOpen\n'
    + '    panel.classList.toggle("open", isOpen)\n'
    + '    fab.classList.toggle("open", isOpen)\n'
    + '    fab.textContent = isOpen ? "×" : "⚡"\n'
    + '    fab.title = isOpen ? "关闭 AI Runner" : "打开 AI Runner (Ctrl+Shift+A)"\n'
    + '    if (isOpen && frame.getAttribute("src") === "about:blank") {\n'
    + '      frame.setAttribute("src", "/__ai/")\n'
    + '      frame.addEventListener("load", function () { window.focus() }, { once: true })\n'
    + '    }\n'
    + '    if (isOpen) window.focus()\n' // [fix-focus-back]
    + '  }\n'
    + '  fab.addEventListener("click", toggle)\n'
    + '  window.addEventListener("message", function (e) {\n'
    + '    if (!e || !e.data) return\n'
    + '    if (e.data.type === "ai-runner:session-id") {\n'
    + '      var f = shadow.getElementById("frame")\n'
    + '      if (f && f.contentWindow) f.contentWindow.postMessage(e.data, "*")\n'
    + '      return\n'
    + '    }\n'
    + '    if (e.data.type !== "ai-runner:close") return\n'
    + '    if (isOpen) toggle()\n'
    + '  })\n'
    + '  window.addEventListener("keydown", function (e) {\n'
    + '    if ((e.metaKey || e.ctrlKey) && e.shiftKey && (e.key === "A" || e.key === "a")) {\n'
    + '      e.preventDefault()\n'
    + '      toggle()\n'
    + '    }\n'
    + '  })\n'
    + '})()'
}
